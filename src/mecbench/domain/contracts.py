"""Read-only structural contracts shared by validation and solver adapters."""

from collections.abc import Mapping, Sequence
from typing import Protocol, TypeAlias

import numpy as np
from numpy.typing import ArrayLike, NDArray

FloatArray: TypeAlias = NDArray[np.float64]
IntArray: TypeAlias = NDArray[np.int64]
ArcArrays: TypeAlias = tuple[FloatArray, FloatArray, FloatArray]


class GraphDimensions(Protocol):
    def number_of_nodes(self) -> int: ...
    def number_of_edges(self) -> int: ...


class NetworkData(Protocol):
    @property
    def nx_graph(self) -> GraphDimensions: ...
    @property
    def arc_list(self) -> Sequence[tuple[int, int]]: ...
    @property
    def arc_index_dictionary(self) -> Mapping[tuple[int, int], int]: ...
    @property
    def available_resources(self) -> Sequence[float]: ...
    @property
    def capacities(self) -> Sequence[float]: ...
    @property
    def alphas(self) -> Sequence[float]: ...
    @property
    def betas(self) -> Sequence[float]: ...


class ProblemData(Protocol):
    @property
    def network_graph(self) -> NetworkData: ...
    @property
    def number_of_service(self) -> int: ...
    @property
    def total_number_of_demands(self) -> int: ...
    @property
    def origins(self) -> Sequence[int]: ...
    @property
    def demand_to_service(self) -> Sequence[int]: ...
    @property
    def needed_resources(self) -> Sequence[float]: ...
    @property
    def min_flows(self) -> Sequence[float]: ...
    @property
    def max_flows(self) -> Sequence[float]: ...
    @property
    def latencies(self) -> Sequence[float]: ...


class SolutionData(Protocol):
    @property
    def x(self) -> ArrayLike: ...
    @property
    def y(self) -> ArrayLike: ...
    @property
    def q(self) -> ArrayLike: ...
